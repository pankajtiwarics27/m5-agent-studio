#!/usr/bin/env python3
"""Generate the product roadmap status dashboard from the roadmap JSON.

The JSON file ``product/Adaptive_Runtime_Product_Roadmap_v2.json`` is the
source of truth for story status. This script validates it and renders
``docs/product-roadmap-status.md``. CI regenerates the dashboard and fails
if the committed copy drifts, so never hand-edit the generated file.
"""
from __future__ import annotations

import argparse
import collections
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ROADMAP = ROOT / "product" / "Adaptive_Runtime_Product_Roadmap_v2.json"
DASHBOARD = ROOT / "docs" / "product-roadmap-status.md"

STATUS_ORDER = ["verified", "completed", "in_progress", "planned"]
STATUS_MARK = {"verified": "✅ Verified", "completed": "🟩 Completed", "in_progress": "🚧 In progress", "planned": "⬚ Planned"}


class RoadmapError(RuntimeError):
    """Raised when the roadmap file is structurally invalid."""


def load_roadmap(path: pathlib.Path = ROADMAP) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise RoadmapError(f"Cannot read {path}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise RoadmapError(f"{path.name} is not valid JSON: {exc}") from exc

    for key in ("milestones", "stories", "status_tracking"):
        if key not in data:
            raise RoadmapError(f"{path.name} is missing required key '{key}'")
    tracking = data["status_tracking"]
    vocabulary = tracking.get("vocabulary")
    if not isinstance(vocabulary, dict) or set(vocabulary) < set(STATUS_ORDER):
        raise RoadmapError("status_tracking.vocabulary must define all statuses: " + ", ".join(STATUS_ORDER))

    stories = data["stories"]
    ids = [s.get("id") for s in stories]
    if any(not i for i in ids):
        raise RoadmapError("Every story needs an id")
    duplicates = [i for i, n in collections.Counter(ids).items() if n > 1]
    if duplicates:
        raise RoadmapError(f"Duplicate story ids: {', '.join(duplicates)}")
    known = set(ids)

    for story in stories:
        status = story.get("status")
        if status not in STATUS_ORDER:
            raise RoadmapError(f"{story.get('id')}: unknown status {status!r}")
        evidence = (story.get("status_evidence") or "").strip()
        if status != "planned" and not evidence:
            raise RoadmapError(f"{story['id']}: non-planned status requires status_evidence")
        for dep in story.get("dependencies") or []:
            if dep not in known:
                raise RoadmapError(f"{story['id']}: dependency {dep} is not a known story")

    milestone_ids = {m.get("id") for m in data["milestones"]}
    for story in stories:
        mid = (story.get("milestone") or {}).get("id")
        if mid not in milestone_ids:
            raise RoadmapError(f"{story['id']}: milestone {mid!r} is not defined")
    return data


def render(data: dict) -> str:
    tracking = data["status_tracking"]
    stories = data["stories"]
    milestone_order = {m["id"]: idx for idx, m in enumerate(data["milestones"])}
    milestones = {m["id"]: m for m in data["milestones"]}

    counts = collections.Counter(s["status"] for s in stories)
    total = len(stories)

    lines: list[str] = []
    lines.append("# Product roadmap status")
    lines.append("")
    lines.append(f"Generated from [`product/Adaptive_Runtime_Product_Roadmap_v2.json`](../product/Adaptive_Runtime_Product_Roadmap_v2.json) "
                 f"(source document v{data['source'].get('document_version', '?')}, planning date {data['source'].get('planning_date', '?')}). "
                 f"Status last updated: **{tracking['last_updated']}**.")
    lines.append("")
    lines.append("> This file is generated by `scripts/generate_roadmap_status.py`; do not edit it by hand. "
                 "Update story status in the JSON, then regenerate and commit both files in the same pull request.")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Status | Count |")
    lines.append("|---|---|")
    for status in STATUS_ORDER:
        lines.append(f"| {STATUS_MARK[status]} | {counts.get(status, 0)} |")
    lines.append(f"| **Total** | **{total}** |")
    lines.append("")
    lines.append("### Status vocabulary")
    lines.append("")
    for status in STATUS_ORDER:
        lines.append(f"- **{status}** — {tracking['vocabulary'][status]}")
    lines.append("")
    lines.append("## Milestones")
    lines.append("")
    for mid in sorted(milestones, key=lambda i: milestone_order[i]):
        m = milestones[mid]
        m_stories = sorted((s for s in stories if s["milestone"]["id"] == mid), key=lambda s: s.get("backlog_order", 0))
        done = sum(1 for s in m_stories if s["status"] in ("verified", "completed"))
        lines.append(f"### {mid} — {m['name']} ({done}/{len(m_stories)} done)")
        lines.append("")
        if m.get("exit_gate"):
            lines.append(f"Exit gate: {m['exit_gate']}")
            lines.append("")
        lines.append("| ID | P | Story | Status | Evidence / remaining work |")
        lines.append("|---|---|---|---|---|")
        for s in m_stories:
            deps = ", ".join(s.get("dependencies") or [])
            deps_note = f" (deps: {deps})" if deps else ""
            evidence = (s.get("status_evidence") or "").strip() or "—"
            evidence = evidence.replace("|", "\\|")
            title = s["title"].replace("|", "\\|")
            lines.append(f"| {s['id']} | {s.get('priority', '?')} | {title}{deps_note} | {STATUS_MARK[s['status']]} | {evidence} |")
        lines.append("")

    adrs = data.get("architecture_decision_records") or []
    if adrs:
        lines.append("## Architecture decision records")
        lines.append("")
        lines.append("The living ADRs are under [`docs/adr/`](adr/README.md); this index reflects the roadmap document.")
        lines.append("")
        lines.append("| ADR | Title | Roadmap status | Review requirement |")
        lines.append("|---|---|---|---|")
        for a in adrs:
            title = str(a.get("title", "")).replace("|", "\\|")
            lines.append(f"| {a.get('id', '?')} | {title} | {a.get('status', '?')} | {a.get('review_requirement', '—')} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed dashboard is not up to date")
    args = parser.parse_args()
    try:
        data = load_roadmap()
        content = render(data)
    except RoadmapError as exc:
        print(f"Roadmap validation failed: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if DASHBOARD.read_text(encoding="utf-8") != content:
            print(f"{DASHBOARD} is stale; run: python scripts/{pathlib.Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"Roadmap dashboard is up to date: {DASHBOARD}")
        return 0
    DASHBOARD.write_text(content, encoding="utf-8")
    print(f"Wrote {DASHBOARD} ({len(data['stories'])} stories)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
