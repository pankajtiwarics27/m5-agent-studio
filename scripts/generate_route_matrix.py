#!/usr/bin/env python3
"""Generate the HTTP route/security coverage inventory from FastAPI's registered routes."""
from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import app  # noqa: E402

OUT = ROOT / "docs" / "route-security-matrix.md"


def rows() -> list[tuple[str, str, str, str]]:
    result: list[tuple[str, str, str, str]] = []
    for route in app.app.routes:
        path = getattr(route, "path", None)
        methods = getattr(route, "methods", None)
        if not path or not methods:
            continue
        for method in sorted(m for m in methods if m not in {"HEAD", "OPTIONS"}):
            if path == "/healthz":
                auth, controls = "Public", "Minimal liveness only; no provider readiness or secrets."
            elif path == "/" or path.startswith("/static"):
                auth, controls = "Public UI/static", "No state-changing API operation; API calls remain subject to API policy."
            elif path in {"/docs", "/redoc", "/openapi.json"}:
                auth, controls = "Optional public API docs", "Registered only when `STUDIO_ENABLE_API_DOCS=1`; avoid enabling on exposed deployments."
            elif path.startswith(("/api/", "/v1/")):
                auth = "Bearer token; generated locally by default or supplied via `STUDIO_API_TOKEN`; mandatory for non-loopback binds"
                controls = "Host allowlist; same-origin check on state-changing requests carrying Origin; auth can be disabled only on loopback via `STUDIO_AUTH_DISABLED=1`."
            else:
                auth, controls = "Review required", "Route is outside the standard API auth-prefix policy."
            result.append((method, path, auth, controls))
    return sorted(set(result), key=lambda r: (r[1], r[0]))


def render() -> str:
    table = [
        "# Generated route/security matrix",
        "",
        "> Generated by `python scripts/generate_route_matrix.py`. Do not edit manually.",
        "> This documents HTTP boundary coverage; route-specific authorization and data validation still require review.",
        "",
        "## Boundary summary",
        "",
        "- Every `/api/*` and `/v1/*` route is covered by the shared host/origin middleware and bearer auth by default.",
        "- Loopback deployments generate a random token file unless `STUDIO_AUTH_DISABLED=1`; non-loopback binds require a configured token at application startup.",
        "- State-changing requests are rejected when a supplied `Origin` is neither same-origin nor in `STUDIO_ALLOWED_ORIGINS`.",
        "- `/healthz`, `/`, and static assets are public. Health is not a readiness probe.",
        "- FastAPI docs/OpenAPI routes are disabled by default; `STUDIO_ENABLE_API_DOCS=1` exposes public documentation endpoints.",
        "- This is not user/tenant authorization; the current app has one operator trust domain.",
        "",
        "## Registered routes",
        "",
        "| Method | Path | Authentication | Additional boundary controls |",
        "|---|---|---|---|",
    ]
    for method, path, auth, controls in rows():
        table.append(f"| `{method}` | `{path}` | {auth} | {controls} |")
    table.append("")
    if any(auth == "Review required" for _, _, auth, _ in rows()):
        raise SystemExit("A registered route is outside the API auth-prefix policy; review it before updating the matrix.")
    return "\n".join(table)


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(rows())} method/path entries)")
