#!/usr/bin/env python3
"""Generate/recheck LC-08 static entry-point inventory; no app import or I/O."""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/runtime-dispatch-entry-points.md"
HELPERS = frozenset(
    {
        "stream_any_model",
        "_stream_omlx_completion",
        "_stream_cloud_openai",
        "_stream_cloud_anthropic",
        "_unload_omlx_model",
        "_unload_other_omlx_models",
    }
)
WIRE_OWNERS = frozenset(
    {
        "_stream_omlx_completion",
        "_stream_cloud_openai",
        "_stream_cloud_anthropic",
        "_unload_omlx_model",
        "_unload_other_omlx_models",
        "api_load_model",
        "api_unload_model",
        "api_unload_all",
        "api_clear_ssd_cache",
    }
)


def inventory(source: str) -> list[tuple[str, str, int]]:
    result = []

    def visit(node: ast.AST, owner: str) -> None:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            owner = f"{owner}.{node.name}" if owner else node.name
        if isinstance(node, ast.Call):
            name = ast.unparse(node.func)
            if name in HELPERS:
                result.append((owner, name, node.lineno))
            # Inspect actual HTTP call arguments, not comments/docstrings. Unknown
            # allocating wire sites need inventory + executable guard tests.
            if (
                isinstance(node.func, ast.Attribute)
                and not (
                    isinstance(node.func.value, ast.Name)
                    and node.func.value.id == "app"
                )
                and node.func.attr
                in (
                    "post",
                    "stream",
                    "request",
                )
            ):
                text = ast.unparse(node)
                if "OMLX_BASE" in text or any(
                    p in text
                    for p in (
                        "/chat/completions",
                        "/api/chat",
                        "/api/generate",
                        "/tokenize",
                    )
                ):
                    if owner not in WIRE_OWNERS:
                        raise ValueError(f"unmapped model wire owner: {owner}")
                    result.append(
                        (
                            owner,
                            "guarded legacy HTTP (not coordinated authority)",
                            node.lineno,
                        )
                    )
        for child in ast.iter_child_nodes(node):
            visit(child, owner)

    visit(ast.parse(source), "")
    return sorted(result)


def render(source: str) -> str:
    rows = inventory(source)
    return (
        """# Runtime dispatch entry points (LC-08, static)

Generated by `scripts/runtime_dispatch_inventory.py`; do not hand-edit.

This inventory identifies application call sites, **not installed qualification,
reachability proof or LC-08 completion**. The rollout default remains legacy.
Coordinated composition intercepts common dispatch/control helpers and fences
raw runtime effects; no production backend or counter is installed. Positive
boundary tests use fake backends, not native-operation authority. Full native
executor, canonical packet consumer, cross-runtime race/recovery evidence and
all-path inclusion validation remain required before activation.

| Owning function | Common seam / guarded wire | app.py line |
|---|---|---:|
"""
        + "".join(f"| `{owner}` | `{via}` | {line} |\n" for owner, via, line in rows)
        + """
## Non-stream observers and unavailable paths

- Onboarding/readiness, catalog and Ollama tags/ps probes perform metadata reads;
  their output is not allocated-context, ownership, terminality or fit proof.
- Tokenizer methods on dormant native bridges remain unavailable. LC-07 rejects
  possibly loading/unqualified counters before effects; no new tokenizer route is
  exposed by this change.
- Calibration A/B uses the common inference callback. Child/critic, GSD/SDLC,
  Council/Debate, MCP summon and model-switch probes enter the seams above.
  Session/grant/checkpoint/handoff semantics still belong to LC-09.
- Coordinated combos currently refuse rather than falling through to legacy,
  another local model or cloud. A complete fit/consent-aware executor is pending.
- Generic private/proxy providers are not inferred to be qualified cloud/native
  runtimes. Explicit backend/alias composition is internal only, not a public
  setting, route or operation permit. Native transports cannot reuse the generic
  HTTP effect path as a bypass.
"""
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render((ROOT / "app.py").read_text())
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("Runtime dispatch inventory is stale; regenerate it.")
            return 1
        print("Runtime dispatch inventory is current.")
    else:
        OUT.write_text(text)
        print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
